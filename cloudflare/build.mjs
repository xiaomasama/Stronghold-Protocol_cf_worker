/** server/sim → dist/sim, `.js` only, nodeData.js excluded (SIM_PRIVATE). */
function copySim(from, to) {
  mkdirSync(to, { recursive: true });
  for (const d of readdirSync(from, { withFileTypes: true })) {
    const src = join(from, d.name);
    const dst = join(to, d.name);
    if (d.isDirectory()) { copySim(src, dst); continue; }
    if (!d.isFile()) continue;
    if (SIM_PRIVATE.has(d.name.toLowerCase())) continue;
    cpSync(src, dst);
  }
}

/** server/index.js computeBuildTag: sha1 over "path\0size\0mtime" of every file under BUILD_INPUTS. */
function computeBuildTag(root) {
  const out = [];
  for (const rel of BUILD_INPUTS) collect(join(root, rel), rel, out);
  if (!out.length) return null;
  out.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
  const h = createHash('sha1');
  for (const [rel, size, mtime] of out) h.update(`${rel}\0${size}\0${Math.floor(mtime)}\n`);
  return h.digest('hex').slice(0, 12);
}

function collect(abs, rel, out) {
  let st;
  try { st = statSync(abs); } catch { return; }
  if (st.isDirectory()) {
    for (const name of readdirSync(abs)) collect(join(abs, name), `${rel}/${name}`, out);
    return;
  }
  if (st.isFile()) out.push([rel.replace(/\\/g, '/'), st.size, st.mtimeMs]);
}

function scan(root, acc = { count: 0, bytes: 0, largest: { file: '', bytes: 0 }, oversize: [] }) {
  for (const d of readdirSync(root, { withFileTypes: true })) {
    const abs = join(root, d.name);
    if (d.isDirectory()) { scan(abs, acc); continue; }
    const st = statSync(abs);
    acc.count++;
    acc.bytes += st.size;
    const rel = relative(root, abs);
    if (st.size > acc.largest.bytes) acc.largest = { file: rel, bytes: st.size };
    if (st.size > MAX_FILE_BYTES) acc.oversize.push({ file: rel, bytes: st.size });
  }
  return acc;
}
